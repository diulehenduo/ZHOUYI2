    private static void put(int seq, int upper, int lower, String name, String symbol,
                            String judgment, String image) {
        int binary = (upper << 3) | lower;
        HEXAGRAMS[binary][0] = String.valueOf(seq);
        HEXAGRAMS[binary][1] = name;
        HEXAGRAMS[binary][2] = symbol;
        HEXAGRAMS[binary][3] = judgment;
        HEXAGRAMS[binary][4] = image;
    }

    /**
     * 根据二进制值查找卦
     *
     * @param binary 六位二进制值（从下往上，阳=1 阴=0），范围 0~63
     * @return 卦信息数组 [序号, 卦名, 符号, 卦辞, 象辞]，未找到返回 null
     */
    public static String[] findByBinary(int binary) {
        if (binary < 0 || binary > 63) {
            return null;
        }
        String[] hex = HEXAGRAMS[binary];
        if (hex[0] == null) {
            return null;
        }
        return hex;
    }

    /**
     * 由 6 个爻的二进制值数组查找卦
     *
     * @param yaos 长度为 6 的数组，从初爻（index=0）到上爻（index=5），值 1(阳) 或 0(阴)
     * @return 卦信息数组
     */
    public static String[] findByYaos(int[] yaos) {
        if (yaos == null || yaos.length != 6) {
            throw new IllegalArgumentException("爻数组必须为 6 个元素");
        }
        int binary = 0;
        for (int i = 0; i < 6; i++) {
            binary |= (yaos[i] & 1) << i;
        }
        return findByBinary(binary);
    }

    /**
     * 获取上卦名称（上三爻）
     */
    public static String getUpperTrigramName(int binary) {
        int upper = (binary >> 3) & 0x7;
        return TRIGRAM_NAMES[upper];
    }

    /**
     * 获取下卦名称（下三爻）
     */
    public static String getLowerTrigramName(int binary) {
        int lower = binary & 0x7;
        return TRIGRAM_NAMES[lower];
    }

    /**
     * 获取上卦自然象征
     */
    public static String getUpperTrigramNature(int binary) {
        int upper = (binary >> 3) & 0x7;
        return TRIGRAM_NATURES[upper];
    }

    /**
     * 获取下卦自然象征
     */
    public static String getLowerTrigramNature(int binary) {
        int lower = binary & 0x7;
        return TRIGRAM_NATURES[lower];
    }
